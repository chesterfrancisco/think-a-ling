import assert from 'node:assert/strict'
import { dismissStory } from './dismiss-story.js'

// Real browser inference. Manual annotations are test user input, not detections.
// Also runnable against the production preview via THINK_TEST_ORIGIN.
export default async function validatePhotoRefinements(page) {
  const origin = process.env.THINK_TEST_ORIGIN || 'http://localhost:5173'
  const context = await page.context().browser().newContext({ viewport: { width: 1280, height: 900 } })
  const tab = await context.newPage()
  const report = { origin, checks: [], external: [], nonReadRequests: [], errors: [] }
  await context.route('**/*', route => {
    const request = route.request()
    if (!['GET', 'HEAD'].includes(request.method())) report.nonReadRequests.push(request.url())
    if (new URL(request.url()).origin === origin) return route.continue()
    report.external.push(request.url()); return route.abort()
  })
  tab.on('pageerror', error => report.errors.push(error.message))
  const ready = () => tab.waitForFunction(() => document.querySelector('.viewfinder')?.dataset.detectionStatus === 'done' && document.querySelector('.viewfinder')?.dataset.ocrStatus === 'done', null, { timeout: 60_000 })
  const boxes = () => tab.locator('.image-stage .image-preview > svg rect').evaluateAll(nodes => nodes.map(node => ['x', 'y', 'width', 'height'].map(key => node.getAttribute(key))))
  const pinAlignment = async (x, y) => {
    const photo = await tab.locator('.image-stage .image-preview img').boundingBox()
    const pin = await tab.locator('.image-stage .manual-tag-pin').first().boundingBox()
    assert(Math.abs(pin.x + pin.width / 2 - photo.x - x * photo.width) < 2, 'Pin x alignment')
    assert(Math.abs(pin.y + pin.height / 2 - photo.y - y * photo.height) < 2, 'Pin y alignment')
    assert(await tab.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No horizontal overflow')
  }
  try {
    await tab.goto(origin)
    await dismissStory(tab)
    assert.equal(await tab.locator('.mascot-orbit .ling-mascot').evaluate(node => getComputedStyle(node).animationName), 'ling-hello')
    assert.equal(await tab.locator('.mascot-orbit .ling-wave').evaluate(node => getComputedStyle(node).animationName), 'ling-wave')
    await tab.emulateMedia({ reducedMotion: 'reduce' })
    assert.equal(await tab.locator('.mascot-orbit .ling-mascot').evaluate(node => getComputedStyle(node).animationName), 'none')
    await tab.emulateMedia({ reducedMotion: 'no-preference' })
    assert.match(await tab.locator('main > footer').innerText(), /Think-a-ling!.*AppBuildersPH Hackathon Prototype.*2026/)
    await tab.getByRole('button', { name: 'About Think-a-ling', exact: true }).click()
    const about = tab.locator('.about-dialog')
    assert.match(await about.innerText(), /Chester Francisco/)
    assert.match(await about.innerText(), /within 24 hours/)
    assert.match(await about.innerText(), /MediaPipe EfficientDet-Lite0/)
    await tab.keyboard.press('Escape')
    assert(await tab.getByRole('button', { name: 'About Think-a-ling', exact: true }).evaluate(node => node === document.activeElement))
    report.checks.push('About credits author, 24-hour hackathon context and actual technologies; Ling moves with reduced-motion support; new footer')

    await tab.locator('input[type=file]').setInputFiles('test-images/cats-and-dogs.jpg')
    await ready()
    const original = await boxes()
    assert.equal(original.length, 4)
    await tab.getByRole('button', { name: 'Help', exact: true }).click()
    assert.match(await tab.locator('.navigation-help').innerText(), /Change photo/)
    assert.match(await tab.locator('.navigation-help').innerText(), /Offline reload or installation is not supported/)
    assert.equal(await tab.locator('.navigation-help p').first().evaluate(node => getComputedStyle(node).textAlign), 'justify')
    await tab.getByRole('button', { name: 'Close help', exact: true }).click()
    await tab.getByRole('button', { name: 'Ask This Space', exact: true }).click()
    assert.equal(await tab.locator('#reasoning-title').innerText(), 'Hello, thinker!')
    await tab.getByRole('button', { name: 'Think you later!', exact: true }).click()

    await tab.getByRole('button', { name: 'Add missing tag', exact: true }).click()
    const placement = tab.getByRole('button', { name: 'Place a tag on the photo', exact: true })
    const surface = await placement.boundingBox()
    await tab.mouse.click(surface.x + surface.width * .25, surface.y + surface.height * .4)
    await tab.getByRole('button', { name: 'Save tag', exact: true }).click()
    assert.match(await tab.locator('.manual-tag-editor [role=alert]').innerText(), /short object name/)
    await tab.getByLabel('Object name', { exact: true }).fill('dog')
    await tab.getByRole('button', { name: 'Save tag', exact: true }).click()
    await tab.getByRole('button', { name: 'Edit Dog 3, added by you', exact: true }).waitFor()
    await pinAlignment(.25, .4)
    assert.deepEqual(await boxes(), original)
    assert.equal(await tab.locator('.detection-hotspot').count(), 4)
    assert.equal(await tab.locator('.manual-tag-pin').count(), 1)
    await tab.locator('.manual-tag-pin').click()
    assert.match(await tab.locator('.manual-tag-editor').innerText(), /no AI confidence score/)
    await tab.getByLabel('Object name', { exact: true }).fill('person')
    await tab.getByRole('button', { name: 'Save tag', exact: true }).click()
    await tab.getByRole('button', { name: 'Edit Person, added by you', exact: true }).waitFor()
    report.checks.push('Pointer placement and rename; user pins separate from 4 real detections; no confidence/boxes fabricated; blank labels rejected')

    await tab.getByRole('button', { name: 'Add missing tag', exact: true }).click()
    await tab.keyboard.press('ArrowRight'); await tab.keyboard.press('ArrowDown'); await tab.keyboard.press('Enter')
    await tab.getByLabel('Object name', { exact: true }).fill('person')
    await tab.getByRole('button', { name: 'Save tag', exact: true }).click()
    assert.equal(await tab.getByRole('button', { name: 'Edit Person 2, added by you', exact: true }).count(), 1)
    await tab.getByRole('button', { name: 'Edit Person 2, added by you', exact: true }).click()
    await tab.getByRole('button', { name: 'Remove tag', exact: true }).click()
    assert.equal(await tab.locator('.manual-tag-pin').count(), 1)
    await tab.getByRole('button', { name: 'Add missing tag', exact: true }).click()
    await tab.keyboard.press('Escape')
    assert.equal(await placement.count(), 0)
    await tab.getByRole('button', { name: 'Detect objects', exact: true }).click()
    await ready()
    assert.deepEqual(await boxes(), original)
    assert.equal(await tab.locator('.manual-tag-pin').count(), 1)
    report.checks.push('Keyboard placement, repeated-name numbering, Escape, deletion and rescan retention')

    for (const width of [390, 360, 320]) {
      await tab.setViewportSize({ width, height: 844 })
      await pinAlignment(.25, .4)
      assert(await tab.getByRole('button', { name: 'Help', exact: true }).isVisible())
      await tab.locator('.manual-tag-pin').click()
      assert(await tab.getByLabel('Object name', { exact: true }).isVisible())
      assert(await tab.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
      await tab.keyboard.press('Escape')
    }
    await tab.locator('.viewfinder').scrollIntoViewIfNeeded()
    await tab.screenshot({ path: 'test-results/photo-refinements-mobile.png', fullPage: true })
    await tab.setViewportSize({ width: 1280, height: 900 })
    await tab.getByRole('button', { name: 'Expand image', exact: true }).click()
    await tab.waitForFunction(() => document.fullscreenElement)
    await pinAlignment(.25, .4)
    await tab.getByRole('button', { name: 'Hide fullscreen markers', exact: true }).click()
    assert.equal(await tab.locator('.manual-tag-pin, .detection-hotspot').count(), 0)
    await tab.getByRole('button', { name: 'Show fullscreen markers', exact: true }).click()
    await pinAlignment(.25, .4)
    await tab.locator('.manual-tag-pin').click()
    await tab.getByRole('dialog', { name: 'Edit your tag', exact: true }).waitFor()
    await tab.waitForFunction(() => !document.fullscreenElement)
    await tab.keyboard.press('Escape')
    report.checks.push('Desktop, 390px, 360px, 320px and native fullscreen alignment; all markers hide/show; editing exits fullscreen')

    const oldUrl = await tab.locator('.image-stage img').getAttribute('src')
    const chooserEvent = tab.waitForEvent('filechooser')
    await tab.getByRole('button', { name: 'Change photo', exact: true }).click()
    const chooser = await chooserEvent
    assert.equal(await tab.locator('.image-stage img').getAttribute('src'), oldUrl, 'Opening picker preserves current photo')
    await chooser.setFiles('test-images/blank.png')
    await ready()
    assert.notEqual(await tab.locator('.image-stage img').getAttribute('src'), oldUrl)
    assert.equal(await tab.locator('.manual-tag-pin, .manual-tag-list').count(), 0)
    assert.equal(await tab.locator('.detection-hotspot').count(), 0)
    await tab.getByRole('button', { name: 'Add missing tag', exact: true }).click()
    await tab.keyboard.press('Enter')
    await tab.getByLabel('Object name', { exact: true }).fill('my note')
    await tab.getByRole('button', { name: 'Save tag', exact: true }).click()
    assert.equal(await tab.locator('.manual-tag-pin').count(), 1)
    assert.equal((await boxes()).length, 0)
    await tab.getByRole('button', { name: 'Back to start', exact: true }).click()
    assert.equal(await tab.locator('.manual-tag-pin, .manual-tag-list').count(), 0)
    report.checks.push('Change photo opens picker directly, preserves photo until file chosen, clears tags on replacement/back; empty detection photo still allows user annotation')
    assert.deepEqual(report.external, [])
    assert.deepEqual(report.nonReadRequests, [])
    assert.deepEqual(report.errors, [])
    report.checks.push('No external requests, inference POSTs or page errors in these interactions')
  } catch (error) { report.failure = error.stack; await tab.screenshot({ path: 'test-results/photo-refinements-failure.png', fullPage: true }) }
  finally { await context.close() }
  return report
}
