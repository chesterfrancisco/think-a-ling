import assert from 'node:assert/strict'
import AxeBuilder from '@axe-core/playwright'
import { dismissStory } from './dismiss-story.js'
export default async function validateResilience(page) {
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 1000 } })
  const tab = await context.newPage()
  const report = { checks: [], errors: [], accessibility: [] }
  const audit = async screen => { const result = await new AxeBuilder({ page: tab }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze(); report.accessibility.push(...result.violations.map(v => ({ screen, id: v.id, impact: v.impact, nodes: v.nodes.map(n => n.target) }))) }
  tab.on('pageerror', e => report.errors.push(e.message))
  const ready = () => tab.waitForFunction(() => document.querySelector('.viewfinder')?.dataset.detectionStatus === 'done' && document.querySelector('.viewfinder')?.dataset.ocrStatus === 'done', null, { timeout: 60000 })
  try {
    await tab.goto('http://127.0.0.1:4173'); await dismissStory(tab)
    assert.equal(await tab.locator('.page-intro h1 br').count(), 0)
    assert.equal(await tab.locator('.home-purpose').count(), 0)
    assert.equal(await tab.getByRole('button', { name: 'Voice question', exact: true }).count(), 0)
    for (const width of [1440, 390, 320]) {
      await tab.setViewportSize({ width, height: 1000 })
      assert(await tab.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No overflow ' + width)
    }
    await tab.setViewportSize({ width: 1440, height: 1000 })
    await tab.getByRole('button', { name: 'Account', exact: true }).click()
    assert.match(await tab.locator('.account-dialog').innerText(), /not connected|Sign in/)
    await audit('account setup dialog')
    await tab.getByRole('button', { name: 'Close account', exact: true }).click()
    await tab.getByText('Reading & accessibility', { exact: true }).click()
    await tab.getByRole('checkbox', { name: 'Pause decorative animation' }).check()
    await tab.getByRole('checkbox', { name: 'Larger reading text' }).check()
    assert(await tab.evaluate(() => document.documentElement.classList.contains('still-ling')))
    await audit('home')
    await tab.getByRole('checkbox', { name: 'Larger reading text' }).uncheck()
    await tab.locator('.offline-setup summary').click()
    await tab.waitForFunction(() => !!navigator.serviceWorker.controller)
    await tab.getByRole('button', { name: /Prepare for offline/ }).click()
    await tab.waitForFunction(() => document.querySelector('.offline-setup summary')?.textContent.includes('Offline pack ready') || document.querySelector('.offline-setup .error'), null, { timeout: 120000 })
    assert.equal(await tab.locator('.offline-setup .error').count(), 0, await tab.locator('.offline-setup').innerText())
    report.checks.push('Explicit hash-verified offline pack completes; no voice icon before analysis; account dialog accessible; keyboard-accessible reading controls')
    await context.setOffline(true)
    await tab.reload(); await dismissStory(tab)
    assert.match(await tab.locator('.offline-setup summary').innerText(), /offline/i)
    assert(await tab.evaluate(() => document.documentElement.classList.contains('still-ling')), 'Accessibility preference persists')
    await tab.locator('input[type=file]').setInputFiles('test-images/ocr-test.png'); await ready()
    await tab.getByRole('button', { name: 'Read text', exact: true }).click()
    await tab.locator('.text-workbench input[type=search]').fill('Invoice')
    assert.match(await tab.locator('.text-workbench [role=status]').innerText(), /12345/)
    await tab.getByRole('button', { name: 'Practice recall from these lines' }).click()
    await tab.locator('.text-workbench details').first().locator('summary').click()
    assert((await tab.locator('.text-workbench details').first().innerText()).includes('LOCAL'))
    await tab.locator('.text-workbench').getByRole('button', { name: 'Save this', exact: true }).click()
    await audit('recognized text and recall')
    await tab.keyboard.press('Escape')
    await tab.getByRole('button', { name: 'Edit photo', exact: true }).click()
    await audit('photo editor')
    const before = await tab.locator('.photo-editor canvas').evaluate(c => ({ w: c.width, h: c.height }))
    await tab.getByRole('button', { name: 'Rotate 90°' }).click()
    await tab.waitForFunction(b => { const c = document.querySelector('.photo-editor canvas'); return c.width === b.h && c.height === b.w }, before)
    await tab.getByRole('button', { name: 'Reset edits' }).click()
    await tab.getByLabel('Crop width:', { exact: false }).fill('80')
    await tab.getByRole('button', { name: 'Apply edits and rescan' }).click()
    await tab.locator('.photo-editor').waitFor({ state: 'detached' }); await ready()
    assert.equal(await tab.locator('.photo-editor').count(), 0)
    assert.equal(await tab.locator('.scene-summary').count(), 0)
    await tab.reload(); await dismissStory(tab)
    await tab.getByRole('button', { name: 'Saved', exact: true }).click()
    assert.match(await tab.locator('.pockets-dialog').innerText(), /Recall practice/)
    await tab.keyboard.press('Escape')
    const missing = await tab.goto('http://127.0.0.1:4173/this-page-does-not-exist')
    assert.equal(missing.status(), 404)
    assert.match(await tab.locator('h1').innerText(), /can’t find/)
    await tab.getByRole('link', { name: 'Back to Think-a-ling' }).click(); await dismissStory(tab)
    await tab.locator('.demo-guide summary').click()
    await tab.getByRole('button', { name: 'Try example study notes', exact: true }).click(); await ready()
    await tab.getByRole('button', { name: 'Read text', exact: true }).click()
    await tab.locator('.text-workbench input[type=search]').fill('Photosynthesis')
    assert.match(await tab.locator('.text-workbench [role=status]').innerText(), /uses light to make food/i)
    await tab.getByRole('button', { name: 'Practice recall from these lines' }).click()
    await tab.locator('.text-workbench').getByRole('button', { name: 'Save this', exact: true }).click()
    await tab.keyboard.press('Escape')
    await tab.locator('input[type=file]').setInputFiles('test-images/cats-and-dogs.jpg'); await ready()
    assert.equal(await tab.locator('.detection-hotspot').count(), 4)
    assert.deepEqual(report.errors, [])
    report.checks.push('Full offline reload; real OCR/search/recall/save; offline crop/rotate and rescan; saved practice survives another reload; Ling 404 returns 404 and recovers; new image has four real detections offline')
    report.checks.push('One-click study example is cached input only; real OCR finds photosynthesis and saves recall practice offline')
    assert.equal(report.accessibility.filter(v => ['serious', 'critical'].includes(v.impact)).length, 0, JSON.stringify(report.accessibility))
  } catch (error) { report.failure = error.stack; await tab.screenshot({ path: 'test-results/resilience-failure.png', fullPage: true }) }
  finally { await context.close() }
  return report
}
